# Авто-добавление кириллических ключей по уже имеющимся городам постсоветских стран (без РФ).
def _ps_norm_keep_spaces(_s):
    _s = (_s or "").strip().lower()
    if not _s:
        return ""
    _s = _s.replace("ё", "е").replace("–", "-").replace("—", "-").replace("−", "-")
    out = []
    prev_space = False
    for ch in _s:
        if ch.isalnum() or ch in (" ", "-"):
            if ch == " ":
                if not prev_space:
                    out.append(" ")
                prev_space = True
            elif ch == "-":
                out.append("-")
                prev_space = False
            else:
                out.append(ch)
                prev_space = False
        else:
            # любой разделитель превращаем в пробел
            if not prev_space:
                out.append(" ")
                prev_space = True
    _s = "".join(out).strip()
    while "  " in _s:
        _s = _s.replace("  ", " ")
    return _s

