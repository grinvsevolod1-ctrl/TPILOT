def _nlq_load(name):
    """Return one data block as dict[str, tuple[str, str]] (byte-identical
    to the old inline literal). Raises on missing file/block so the import
    fails loudly rather than silently degrading geo detection."""
    global _NLQ_BLOCKS
    if _NLQ_BLOCKS is None:
        with _NLQ_JSON.open(encoding="utf-8") as _f:
            _NLQ_BLOCKS = _json.load(_f)["blocks"]
    return {k: (v[0], v[1]) for k, v in _NLQ_BLOCKS[name].items()}


